"""
RCON Warfare — диспетчерская боевой техники для Minecraft через RCON.

Пакет ядра. Не зависит от графической библиотеки: любой модуль здесь можно
импортировать и использовать из CLI, из тестов или из бота без UI.

Слои архитектуры
----------------
    config.py       настройки, загрузка/сохранение JSON
    events.py       шина событий (ядро -> UI, без обратных зависимостей)
    rcon.py         протокол Source RCON: соединение, пул, очередь команд
    mock_server.py  офлайн-имитация сервера Minecraft (для тестов и демо)
    world.py        состояние мира: игроки, юниты, маршруты, рельеф, зоны
    mc.py           билдеры команд Minecraft + определение возможностей сервера
    geometry.py     чистая математика (углы, векторы) — один источник правды
    units.py        техника (самолёт/вертолёт/дрон/танк) и физика
    routes.py       waypoints, действия, исполнитель маршрута
    ai.py           генераторы маршрутов для ботов
    weapons.py      огонь, боезапас, баллистика
    maprender.py    слои карты и рендер в примитивы
    ui/             интерфейс на Dear PyGui (см. ARCHITECTURE.md)
"""

