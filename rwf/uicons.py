def _rot(pts: Sequence[Tuple[float, float]], deg: float,
         cx: float = 12.0, cy: float = 12.0) -> List[Tuple[float, float]]:
    a = math.radians(deg)
    ca, sa = math.cos(a), math.sin(a)
    out = []
    for x, y in pts:
        dx, dy = x - cx, y - cy
        out.append((cx + dx * ca - dy * sa, cy + dx * sa + dy * ca))
    return out


def _plane_tilt(deg: float, scale: float, dy: float) -> List[Op]:
    pts = [(12 + (x - 12) * scale, 12 + (y - 12) * scale) for x, y in _PLANE_TOP]
    return [("p", _rot(pts, deg, 12.0, 12.0 - dy), True)]


