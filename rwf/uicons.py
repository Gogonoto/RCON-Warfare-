DEFAULT_ICON = "target"

# ---------------------------------------------------------------------------
#  Генерация примитивов
# ---------------------------------------------------------------------------
_ARC_STEP = 10.0


def ops(name: str) -> List[Op]:
    return ICONS.get(name, ICONS[DEFAULT_ICON])


def prims(name: str, x: float, y: float, size: float, color,
          width: float = 1.7, alpha: Optional[int] = None) -> List[Prim]:
    """Иконка с центром (x, y), габаритом size px -> примитивы painter'а."""
    s = size / 24.0
    out: List[Prim] = []

    def px(vx: float) -> float:
        return x + (vx - 12.0) * s

    def py(vy: float) -> float:
        return y + (vy - 12.0) * s

    w = max(1.0, width * s * 1.55)      # штрих Lucide ~2/24 от габарита
    for op in ops(name):
        kind = op[0]
        if kind == "l":
            out.append({"type": "line", "x1": px(op[1]), "y1": py(op[2]),
                        "x2": px(op[3]), "y2": py(op[4]), "color": color,
                        "width": w, "alpha": alpha})
        elif kind == "p":
            pts = [(px(vx), py(vy)) for vx, vy in op[1]]
            out.append({"type": "poly", "points": pts, "closed": bool(op[2]),
                        "outline": color, "width": w, "alpha": alpha})
        elif kind == "c":
            out.append({"type": "circle", "x": px(op[1]), "y": py(op[2]),
                        "r": op[3] * s, "outline": color, "width": w,
                        "alpha": alpha})
        elif kind == "d":
            out.append({"type": "circle", "x": px(op[1]), "y": py(op[2]),
                        "r": max(1.0, op[3] * s), "fill": color,
                        "outline": color, "width": 1, "alpha": alpha})
        elif kind == "a":
            cx, cy, r, a0, a1 = op[1], op[2], op[3], op[4], op[5]
            n = max(2, int(abs(a1 - a0) / _ARC_STEP) + 1)
            pts = []
            for i in range(n + 1):
                a = math.radians(a0 + (a1 - a0) * i / n)
                pts.append((px(cx + r * math.cos(a)), py(cy + r * math.sin(a))))
            out.append({"type": "poly", "points": pts, "closed": False,
                        "outline": color, "width": w, "alpha": alpha})
    return out


def names() -> List[str]:
    return sorted(ICONS)
