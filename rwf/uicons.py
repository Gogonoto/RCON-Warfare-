"""
Векторные иконки в стиле Lucide (штриховая графика, сетка 24×24).

Зачем свои, а не шрифт-иконки: DPG 2.x не умеет сливать два шрифта в одну
атлас-гарнитуру, а отдельная гарнитура с иконками не содержит кириллицы.
Штриховая векторная иконка рисуется примитивами `painter` в ЛЮБОМ масштабе
(кнопки, заголовки доков, маркеры баз на карте) и не тянет внешних файлов.

Геометрия хранится в условной сетке 24×24 (как у Lucide: stroke 2, круглые
окончания). `prims()` переводит иконку в примитивы painter'а с центром в
(x, y) и габаритом `size` px; `ops()` — низкоуровневый список операций.

Операции:
    ("l", x1, y1, x2, y2)          линия
    ("p", [(x, y), ...], closed)   полилиния/полигон
    ("c", cx, cy, r)               окружность
    ("a", cx, cy, r, a0, a1)       дуга, градусы (0 = +X, по часовой на экране)
    ("d", cx, cy, r)               залитая точка
"""
